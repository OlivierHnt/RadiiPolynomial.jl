"""
    evensym(s::BaseSpace)

Restrict `s` to the subspace of sequences invariant under the natural involution
of its basis:
- `Fourier`: identifies the modes `k` and `-k`, keeping `k ≥ 0` (cosine series).
- `Taylor` and `Chebyshev`: keeps the even orders only.

# Examples

```jldoctest
julia> collect(indices(evensym(Fourier(3, 1.0))))
4-element Vector{Int64}:
 0
 1
 2
 3

julia> collect(indices(evensym(Taylor(4))))
3-element Vector{Int64}:
 0
 2
 4
```

See also: [`oddsym`](@ref), [`d4sym`](@ref) and [`SymmetricSpace`](@ref).
"""
evensym(s::Taylor) = SymmetricSpace(s,
    Group(GroupElement(LatticeAut(StaticArrays.SMatrix{1,1,Int}(1)),
                       Cocycle(exact(1//1), StaticArrays.SVector{1,Rational{Int}}(1//1)))))
evensym(s::Fourier) = SymmetricSpace(s,
    Group(GroupElement(LatticeAut(StaticArrays.SMatrix{1,1,Int}(-1)),
                       Cocycle(exact(1//1), StaticArrays.SVector{1,Rational{Int}}(0//1)))))
evensym(s::Chebyshev) = SymmetricSpace(s,
    Group(GroupElement(LatticeAut(StaticArrays.SMatrix{1,1,Int}(1)),
                       Cocycle(exact(1//1), StaticArrays.SVector{1,Rational{Int}}(1//1)))))

"""
    oddsym(s::BaseSpace)

Restrict `s` to the subspace of sequences anti-invariant under the natural
involution of its basis:
- `Fourier`: identifies the modes `k` and `-k` together with a sign flip, keeping `k > 0` (since series).
- `Taylor` and `Chebyshev`: keeps the odd orders only.

# Examples

```jldoctest
julia> collect(indices(oddsym(Fourier(3, 1.0))))
3-element Vector{Int64}:
 1
 2
 3

julia> collect(indices(oddsym(Taylor(4))))
2-element Vector{Int64}:
 1
 3
```

See also: [`evensym`](@ref), [`d4sym`](@ref) and [`SymmetricSpace`](@ref).
"""
oddsym(s::Taylor)  = SymmetricSpace(s,
    Group(GroupElement(LatticeAut(StaticArrays.SMatrix{1,1,Int}(1)),
                       Cocycle(exact(-1//1), StaticArrays.SVector{1,Rational{Int}}(1//1)))))
oddsym(s::Fourier)  = SymmetricSpace(s,
    Group(GroupElement(LatticeAut(StaticArrays.SMatrix{1,1,Int}(-1)),
                       Cocycle(exact(-1//1), StaticArrays.SVector{1,Rational{Int}}(0//1)))))
oddsym(s::Chebyshev)  = SymmetricSpace(s,
    Group(GroupElement(LatticeAut(StaticArrays.SMatrix{1,1,Int}(1)),
                       Cocycle(exact(-1//1), StaticArrays.SVector{1,Rational{Int}}(1//1)))))

