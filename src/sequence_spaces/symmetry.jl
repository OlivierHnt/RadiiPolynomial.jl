"""
    d4sym(s::TensorSpace{<:Tuple{<:Fourier,<:Fourier}})

Restrict a two-dimensional Fourier space to the subspace invariant under the
dihedral group ``D_4``, i.e., the symmetries of the square, generated by a
quarter turn and a diagonal reflection.

# Examples

```jldoctest
julia> s = Fourier(2, 1.0) ⊗ Fourier(2, 1.0)
Fourier(2, 1.0) ⊗ Fourier(2, 1.0)

julia> indices(d4sym(s))
6-element Vector{Tuple{Int64, Int64}}:
 (0, 0)
 (1, 0)
 (2, 0)
 (1, 1)
 (2, 1)
 (2, 2)
```

See also: [`evensym`](@ref), [`oddsym`](@ref) and [`SymmetricSpace`](@ref).
"""
d4sym(s::TensorSpace{T}) where {T<:Tuple{<:Fourier,<:Fourier}} = SymmetricSpace(s,
    Group(
        GroupElement(LatticeAut(StaticArrays.SMatrix{2,2,Int}([0 -1 ; 1 0])),
                       Cocycle(exact(1//1), StaticArrays.SVector{2,Rational{Int}}(0//1, 0//1))),
        GroupElement(LatticeAut(StaticArrays.SMatrix{2,2,Int}([0  1 ; 1 0])),
                       Cocycle(exact(1//1), StaticArrays.SVector{2,Rational{Int}}(0//1, 0//1)))))
