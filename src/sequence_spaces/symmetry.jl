"""
    Group(g::GroupElement, h::GroupElement...)

The group generated by the given elements. It is closed under composition at
construction, so [`elements`](@ref) returns every element and not only the
generators.

See also: [`GroupElement`](@ref) and [`SymmetricSpace`](@ref).
"""
struct Group{N,T<:Number}
    elements :: Set{GroupElement{N,T}}
    # a `Group` is never mutated once closed, so its hash is computed once here
    # storing the hash helps with every lookup in `_orbit_cache` when constructing symmetric spaces
    hash     :: UInt
    global function unsafe_group!(elements::Set{GroupElement{N,T}}) where {N,T<:Number}
        # modify in-place the input set of group elements until it is closed under composition (O(|G|²))
        changed = true
        while changed
            changed = false
            for g ∈ elements, h ∈ elements
                gh = g ∘ h
                if gh ∉ elements
                    push!(elements, gh)
                    changed = true
                end
            end
        end
        return new{N,T}(elements, hash(elements))
    end
end

Group(g::GroupElement{N,T}, h::GroupElement{N,T}...) where {N,T<:Number} = unsafe_group!(Set{GroupElement{N,T}}((g, h...)))

"""
    elements(g::Group)

Return the set of [`GroupElement`](@ref)s of `g`. The group is closed under
composition at construction, so this is the full group and not just the
generators it was built from.

See also: [`Group`](@ref) and [`symmetry`](@ref).
"""
elements(g::Group) = g.elements

Base.:(==)(G₁::Group, G₂::Group) = G₁ === G₂ || (G₁.hash == G₂.hash && elements(G₁) == elements(G₂)) # elements(G₁) == elements(G₂) is a safeguard
Base.issubset(G₁::Group, G₂::Group) = issubset(elements(G₁), elements(G₂))
function Base.intersect(G₁::Group, G₂::Group)
    G₁ == G₂ && return G₁
    return unsafe_group!(intersect(elements(G₁), elements(G₂)))
end
function Base.union(G₁::Group, G₂::Group)
    G₁ == G₂ && return G₁
    return Group(elements(G₁)..., elements(G₂)...)
end

Base.hash(g::Group, h::UInt) = hash(g.hash, h)

_orbit(sym::Group{1}, k::T) where {T<:Integer} = Set{T}(g.lattice_aut(k) for g ∈ elements(sym))
_orbit(sym::Group{N}, k::NTuple{N,T}) where {N,T<:Integer} = Set{NTuple{N,T}}(g.lattice_aut(k) for g ∈ elements(sym))

function _orbit_representatives(sym::Group, inds) # slow
    sym_elements = elements(sym)
    T_k = eltype(inds)
    k_reps = Vector{T_k}(undef, length(inds))
    for (i, k) ∈ enumerate(inds)
        k_rep = k
        for g ∈ sym_elements
            k_g = g.lattice_aut(k)
            if k_g > k_rep
                k_rep = k_g
            end
        end
        @inbounds k_reps[i] = k_rep
    end
    return k_reps
end

function _filter_valid_representatives(sym::Group, k_reps)
    sym_elements = elements(sym)
    T_k = eltype(k_reps)
    reps = T_k[]
    seen_reps = Set{T_k}()
    for k_rep ∈ k_reps
        k_rep in seen_reps && continue
        push!(seen_reps, k_rep)

        is_valid_orbit = true # if `k` maps to itself and has a conflicting phase, then it is not a valid orbit
        for g ∈ sym_elements
            if g.lattice_aut(k_rep) == k_rep && g.cocycle(k_rep) != 1
                is_valid_orbit = false
                break
            end
        end
        if is_valid_orbit
            push!(reps, k_rep)
        end
    end
    return _sort_representatives!(reps)
end

_sort_representatives!(reps::Vector{<:Integer}) = sort!(reps)
_sort_representatives!(reps::Vector{<:NTuple{N,Integer}}) where {N} = sort!(reps; by = reverse)

function _compute_action_map(sym::Group, inds, k_reps)
    sym_elements = elements(sym)
    return map(enumerate(inds)) do (i, k)
        # invariance under `g` reads a_k = α_g(k) a_{β_g(k)}, so the element to look for is the
        # one carrying `k` onto its representative, and the factor is its cocycle *at k*
        k_rep = k_reps[i]
        for g ∈ sym_elements
            if g.lattice_aut(k) == k_rep
                return (k_rep, g.cocycle(k))
            end
        end
        return throw(ArgumentError("Symmetry group consistency error"))
    end
end



